def poll_rhythm(poll_minutes: float) -> str:
    """Диапазон базового интервала в минутах с джиттером — для честных текстов
    (теперь интервал настраивается env-ом, «ровно N минут» писать нельзя)."""
    return f"~{poll_minutes * POLL_JITTER[0]:.0f}–{poll_minutes * POLL_JITTER[1]:.0f}"

